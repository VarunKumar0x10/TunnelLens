/* Local browser rehearsal. Uses the app-bundled Playwright and installed Chrome. */
const { chromium } = require('C:/Users/Dino King/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({headless:true, executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const failures=[];
    let expectingBadRequest=false;
    page.on('pageerror', error => failures.push(error.message));
    page.on('console', message => {if(message.type()==='error'&&!(expectingBadRequest&&message.text().includes('400 (Bad Request)')))failures.push(message.text());});
    await page.goto('http://127.0.0.1:8000');
    await page.getByText('Local analyzer ready', {exact:true}).waitFor();
    await page.locator('.sample-card').first().click();
    await page.locator('#processing').waitFor({state:'hidden'});
    await page.locator('#results').waitFor({state:'visible'});
    assert.match(await page.locator('#sessions').innerText(), /AES-GCM-16-256/);
    assert.match(await page.locator('#report-meta').innerText(), /SYNTHETIC/);
    await page.locator('#sessions .evidence-ref').first().click();
    assert.equal(await page.locator('#evidence-body tr').count(),1);
    await page.getByRole('button',{name:'Clear',exact:true}).click();
    assert.ok(await page.locator('#evidence-body tr').count()>1);
    await page.locator('[data-tab="traffic"]').click();
    assert.match(await page.locator('#tab-traffic').innerText(),/Real-capture accuracy is not yet validated/);
    await page.locator('[data-tab="model"]').click();
    assert.match(await page.locator('#model-metrics').innerText(),/Synthetic macro-F1/);
    assert.match(await page.locator('#model-metrics').innerText(),/Pending/);
    await page.locator('.sample-card').nth(1).click();
    await page.locator('#processing').waitFor({state:'hidden'});
    assert.match(await page.locator('#sessions').innerText(),/3DES/);
    assert.match(await page.locator('#metrics').innerText(),/80 \/ 100/);
    await page.locator('[data-tab="security"]').click();
    assert.ok(await page.locator('#finding-body .fail').count()>=4);
    const reportPromise=page.waitForEvent('popup');
    await page.locator('#print-export').click();
    const report=await reportPromise;await report.waitForLoadState();
    assert.match(await report.locator('body').innerText(),/Packet evidence/);
    assert.match(await report.locator('body').innerText(),/Synthetic protocol fixture/);
    await report.close();
    await page.locator('.sample-card').nth(2).click();
    await page.locator('#processing').waitFor({state:'hidden'});
    assert.match(await page.locator('#summary-content').innerText(),/Insufficient evidence/);
    await page.locator('#file-input').setInputFiles(path.join(__dirname,'../samples/captures/synthetic-modern.pcap'));
    await page.locator('#analyze').click();
    await page.locator('#processing').waitFor({state:'hidden'});
    assert.match(await page.locator('#sessions').innerText(),/AES-GCM-16-256/);
    const downloadPromise=page.waitForEvent('download');
    await page.locator('#json-export').click();
    const download=await downloadPromise;
    const downloaded=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
    assert.equal(downloaded.source_kind,'synthetic_fixture');
    const output=path.join(__dirname,'../tmp/browser');fs.mkdirSync(output,{recursive:true});
    await page.evaluate(()=>scrollTo(0,0));
    await page.screenshot({path:path.join(output,'dashboard-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(output,'dashboard-mobile.png'),fullPage:true});
    const dimensions=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
    assert.ok(dimensions.scroll<=dimensions.width,JSON.stringify(dimensions));
    await page.locator('#reset').click();
    await page.locator('#empty-state').waitFor({state:'visible'});
    await page.locator('#file-input').setInputFiles({name:'bad.pcap',mimeType:'application/octet-stream',buffer:Buffer.from('invalid')});
    expectingBadRequest=true;
    await page.locator('#analyze').click();
    await page.locator('#processing').waitFor({state:'hidden'});
    assert.match(await page.locator('#error').innerText(),/signature/);
    await page.locator('.sample-card').first().click();
    await page.locator('#processing').waitFor({state:'hidden'});
    await page.locator('#results').waitFor({state:'visible'});
    assert.equal(await page.locator('#error').isVisible(),false);
    assert.deepEqual(failures,[]);
    for(const sampleId of ['real-time-like','bursty-streaming-like','bulk-transfer-like']){
      await page.locator(`[data-sample-id="${sampleId}"]`).click();
      await page.locator('#processing').waitFor({state:'hidden'});
      await page.locator('[data-tab="traffic"]').click();
      assert.equal(await page.locator('#inference-result').innerText(),sampleId.replaceAll('-',' '));
      assert.match(await page.locator('#report-meta').innerText(),/GENERATED ESP BENCHMARK/);
      assert.ok(await page.locator('#prediction-body tr').count()>=2);
    }
    await page.locator('[data-sample-id="out-of-envelope"]').click();
    await page.locator('#processing').waitFor({state:'hidden'});
    await page.locator('[data-tab="traffic"]').click();
    assert.match(await page.locator('#inference-result').innerText(),/Insufficient evidence/);
    assert.match(await page.locator('#prediction-body').innerText(),/outside training envelope/);
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('[data-sample-id="bursty-streaming-like"]').click();
    await page.locator('#processing').waitFor({state:'hidden'});
    await page.locator('[data-tab="traffic"]').click();
    await page.evaluate(()=>scrollTo(0,0));
    await page.screenshot({path:path.join(output,'tierb-inference-desktop.png'),fullPage:true});
    await page.locator('#demo-toggle').click();
    assert.equal(await page.locator('.upload-panel').isVisible(),false);
    await page.locator('[data-tab="model"]').click();
    await page.evaluate(()=>scrollTo(0,0));
    await page.screenshot({path:path.join(output,'tierb-model-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:path.join(output,'tierb-model-mobile.png'),fullPage:true});
    await page.locator('#demo-toggle').click();
    assert.equal(await page.locator('.upload-panel').isVisible(),true);
    assert.deepEqual(failures,[]);
    console.log('PASS: Tier A workflow plus Tier B signature demos, abstention, model evaluation, charts, presentation mode and mobile layout.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
